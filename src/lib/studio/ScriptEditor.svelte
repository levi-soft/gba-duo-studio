<script lang="ts">
  import {t as uiText} from './i18n.js';
  import type {Project} from './types.js';
  import {PACK_LIMITS,safePackPath} from './pack-safety.js';
  let {project,onchange}: {project:Project;onchange:(project:Project)=>void}=$props();
  const starter='function update()\n  return { hp = mem.u8(0x02000000) }\nend\n';
  let path=$state('scripts/main.lua'),source=$state(starter),error=$state(''),initialized=$state(false);
  const scripts=$derived(Object.keys(project.files).filter(path=>/\.lua$/i.test(path)));
  function decode(path:string){return new TextDecoder().decode(Uint8Array.from(atob(project.files[path]??''),c=>c.charCodeAt(0)));}
  function choose(next:string){path=next;source=project.files[next]?decode(next):starter;error='';}
  $effect(()=>{if(!initialized){initialized=true;choose(project.manifest.script??scripts[0]??'scripts/main.lua');}});
  function save(){
    try{safePackPath(path);if(!/\.lua$/i.test(path))throw Error('extension');}catch{error=$uiText('Đường dẫn Lua không hợp lệ.');return;}
    const custom=source.replace(/^-- Generated by GBA Duo Studio:[^\n]*\n/,'-- Custom Lua edited in GBA Duo Studio\n');
    const bytes=new TextEncoder().encode(custom);let binary='';for(const byte of bytes)binary+=String.fromCharCode(byte);
    onchange({...project,files:{...project.files,[path]:btoa(binary)},manifest:{...project.manifest,script:path}});error='';
  }
  async function importFile(event:Event){
    const input=event.currentTarget as HTMLInputElement,file=input.files?.[0];if(!file)return;
    try{if(file.size>PACK_LIMITS.file)throw Error('Lua file exceeds the 32 MiB limit.');path='scripts/'+file.name;source=await file.text();error='';}catch(errorValue){error=String(errorValue);}finally{input.value='';}
  }
</script>
<details class="script-editor">
  <summary>{$uiText('Script Lua')}</summary>
  <p>{$uiText('Dùng địa chỉ RAM đơn giản không cần Lua. Với logic riêng, nhập hoặc sửa script bên dưới; Studio không chạy Lua trên máy tính.')}</p>
  <label>{$uiText('Script đang dùng')}<select value={project.manifest.script??''} onchange={e=>{const script=e.currentTarget.value;onchange({...project,manifest:{...project.manifest,script:script||undefined}});if(script)choose(script);}}><option value="">{$uiText('Chỉ dùng trường RAM')}</option>{#each scripts as file}<option value={file}>{file}</option>{/each}</select></label>
  <div class="script-toolbar"><button onclick={()=>choose('scripts/main.lua')}>{$uiText('Script mới')}</button><label class="file-button">{$uiText('Nhập file Lua')}<input type="file" accept=".lua,text/plain" onchange={importFile} /></label></div>
  <label>{$uiText('Đường dẫn trong pack')}<input bind:value={path} spellcheck="false" /></label>
  <label>{$uiText('Mã Lua')}<textarea rows="12" bind:value={source} spellcheck="false"></textarea></label>
  {#if error}<p class="error" role="alert">{error}</p>{/if}
  <button class="primary" onclick={save}>{$uiText('Lưu và dùng script này')}</button>
</details>
