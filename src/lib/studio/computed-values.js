import {validateMemorySpecs,memoryHex,memoryTypes} from './memory-values.js';
import {validatePulse,pulseLua} from './pulse-values.js';
import {graphicsLua} from './rom-graphics.js';
/** @typedef {import('./types.js').Scalar} Scalar */
/** @typedef {import('./types.js').Expression} Expression */
/** @typedef {import('./types.js').ExpressionOp} Op */
export const computedScriptPath='scripts/studio-computed.lua';
const generatedMarker='-- Generated by GBA Duo Studio: game-neutral memory fields and expressions.';
/** @param {string} key */
const safeKey=key=>/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)&&!['__proto__','constructor','prototype'].includes(key);
/** @template T
 * @param {Expression} node @param {(key:string)=>T} field
 * @param {(key:T,table:Record<string,Scalar>)=>T} lookup
 * @param {(op:Op,args:T[])=>T} operation @param {(value:Scalar)=>T} literal @param {number} [depth]
 * @returns {T}
 */
function expression(node,field,lookup,operation,literal,depth=0){
  if(depth>12)throw Error('Expression nesting exceeds 12 levels.');
  if(typeof node==='string'||typeof node==='boolean'||typeof node==='number'&&Number.isFinite(node))return literal(node);
  if(!node||typeof node!=='object')throw Error('Invalid expression.');
  if(node.field){if(!safeKey(node.field))throw Error('Invalid expression field name.');return field(node.field);}
  /** @param {Expression} child */
  const visit=child=>expression(child,field,lookup,operation,literal,depth+1);
  if(node.lookup!==undefined){
    if(!node.table||Object.keys(node.table).length>512||Object.values(node.table).some(v=>!['string','number','boolean'].includes(typeof v)||typeof v==='number'&&!Number.isFinite(v)))throw Error('Invalid lookup table.');
    return lookup(visit(node.lookup),node.table);
  }
  const op=node.op,args=node.args;
  if(!op||!['choose','eq','ge','and','or','first','add','sub','mul','max','mod','divfloor'].includes(op)||!Array.isArray(args)||args.length<2||args.length>16)throw Error('Unsupported expression.');
  if(op==='choose'&&args.length!==3||['eq','ge','mod','divfloor'].includes(op)&&args.length!==2)throw Error('Incorrect expression argument count.');
  return operation(op,args.map(visit));
}
/** @param {import('./types.js').DataValues} values @param {Record<string,Expression>} [definitions] */
export function applyComputedValues(values,definitions={}){
  const result={...values};
  for(const [key,node]of Object.entries(definitions)){
    if(!safeKey(key))throw Error('Invalid computed field name.');
    const value=expression(node,k=>{
      const value=result[k];if(typeof value!=='number'&&typeof value!=='boolean'&&typeof value!=='string')throw Error('Missing scalar field '+k);return value;
    },(key,table)=>{
      if(!Object.hasOwn(table,String(key)))throw Object.assign(Error('Lookup table has no value for '+key),{identityMismatch:true});
      return table[String(key)];
    },(op,args)=>{
      if(op==='choose')return args[0]?args[1]:args[2];
      if(op==='eq')return args[0]===args[1];
      if(op==='and')return args.every(Boolean);
      if(op==='or')return args.some(Boolean);
      if(op==='first')return args.find(v=>v!=='')??'';
      const numbers=args.map(value=>{if(typeof value!=='number'||!Number.isFinite(value))throw Error('Arithmetic needs finite numbers.');return value;});
      if(op==='ge')return numbers[0]>=numbers[1];
      if((op==='mod'||op==='divfloor')&&numbers[1]===0)throw Error('Division by zero.');
      const value=op==='add'?numbers.reduce((a,b)=>a+b):op==='sub'?numbers.reduce((a,b)=>a-b):op==='mul'?numbers.reduce((a,b)=>a*b):op==='mod'?((numbers[0]%numbers[1])+numbers[1])%numbers[1]:op==='divfloor'?Math.floor(numbers[0]/numbers[1]):Math.max(...numbers);
      if(!Number.isFinite(value))throw Error('Expression result is not finite.');return value;
    },value=>value);
    result[key]=value;
  }
  return result;
}
/** Preserve custom Lua; regenerate only scripts bearing our own marker.
 * @param {import('./types.js').Project} project */
export function shouldGenerateScript(project){
  const {manifest,files}=project;
  if(manifest.script&&files[manifest.script]){
    if(manifest.script!==computedScriptPath)return false;
    try{if(!atob(files[manifest.script]).startsWith(generatedMarker))return false;}catch{return false;}
  }
  return (!manifest.script||manifest.script===computedScriptPath)&&Boolean(manifest.studioComputed||manifest.studioPulse||Object.keys(manifest.studioGraphics??{}).length);
}
/** @param {Scalar} value */
const luaLiteral=value=>{
  if(typeof value==='string')return '"'+Array.from(new TextEncoder().encode(value),b=>'\\'+String(b).padStart(3,'0')).join('')+'"';
  if(typeof value==='boolean'||typeof value==='number'&&Number.isFinite(value))return String(value);
  throw Error('Unsupported expression literal.');
};
/** @param {import('./types.js').Manifest} manifest */
export function computedLua(manifest){
  validateMemorySpecs(manifest.values??{});
  if(manifest.studioPulse)validatePulse(manifest.studioPulse);
  const lines=[generatedMarker,
    'local function truth(v) return v~=nil and v~=false and v~=0 and v~="" end',
    'local function choose(c,a,b) if truth(c) then return a else return b end end',
    'local function all(...) for i=1,select("#",...) do if not truth(select(i,...)) then return false end end return true end',
    'local function any(...) for i=1,select("#",...) do if truth(select(i,...)) then return true end end return false end',
    'local function first(...) for i=1,select("#",...) do local v=select(i,...) if v~=nil and v~="" then return v end end return "" end',
    'local function read(addr,size,kind) if not ((addr>=0x02000000 and addr+size<=0x02040000) or (addr>=0x03000000 and addr+size<=0x03008000)) then return nil end return mem[kind](addr) end'];
  /** @type {string[]} */
  const tables=[];
  const expressionLines=Object.entries(manifest.studioComputed??{}).map(([key,node])=>{
    if(!safeKey(key))throw Error('Invalid computed field name.');
    const result=expression(node,k=>'v['+luaLiteral(k)+']',(ref,table)=>{
      const name='values'+tables.length;
      tables.push('local '+name+'={'+Object.entries(table).map(([k,v])=>'['+luaLiteral(k)+']='+luaLiteral(v)).join(',')+'}');
      return name+'[tostring('+ref+')]';
    },(op,args)=>{
      if(op==='choose'||op==='first')return op+'('+args.join(',')+')';
      if(op==='and'||op==='or')return (op==='and'?'all':'any')+'('+args.join(',')+')';
      if(op==='eq'||op==='ge')return '('+args[0]+(op==='eq'?'==':'>=')+args[1]+')';
      if(op==='max')return 'math.max('+args.join(',')+')';
      if(op==='divfloor')return 'math.floor('+args[0]+'/'+args[1]+')';
      const symbol={add:'+',sub:'-',mul:'*',mod:'%'}[op];return '('+args.join(symbol)+')';
    },luaLiteral);
    return 'v['+luaLiteral(key)+']='+result;
  });
  lines.push(...tables,'local studioPulseTick=0','function update()','local v={}');
  for(const[key,spec]of Object.entries(manifest.values??{})){
    if(!safeKey(key))throw Error('Invalid memory field name.');
    const address=spec.addr?String(memoryHex(spec.addr)):'(mem.u32('+memoryHex(spec.ptr??'')+')+'+(spec.offset??0)+')';
    let value='read('+address+','+memoryTypes[spec.type]+','+luaLiteral(spec.type)+')';
    if(spec.mask!=null)value='(('+value+' or 0) & '+memoryHex(spec.mask)+')';
    if(spec.shift)value='(('+value+' or 0) >> '+spec.shift+')';
    lines.push('v['+luaLiteral(key)+']='+value);
  }
  lines.push(...expressionLines,...graphicsLua(manifest),...pulseLua(manifest.studioPulse,manifest.tickHz??4),'return v','end','');
  return lines.join('\n');
}
